"""Declarative pipeline step registry — the single source of truth for the
processing pipeline, shared by the FastAPI server and (future) the CLI.

Design rules:
- Steps are DATA, not code: id, title, stage, callables, done-markers, logs.
- Callables are resolved LAZILY (module path + function name) so importing
  this module never pulls heavy dependencies (whisperx / torch / spacy).
- Done-state is derived from artifact files on disk (same rules the old
  Streamlit UI used implicitly), so UI, server and CLI always agree.
- The input/download step is intentionally NOT here: it takes user input
  (url/file) and belongs to the input bar, not the processing pipeline.
"""

from __future__ import annotations

import importlib
import os
from dataclasses import dataclass, field


@dataclass(frozen=True)
class Step:
    id: str                      # stable machine id, used by API/logs
    title: str                   # display name (zh)
    stage: str                   # "sub" (subtitles) | "dub" (dubbing)
    calls: tuple                 # ((module_path, func_name), ...) run in order
    markers: tuple = ()          # artifact paths proving completion
    marker_mode: str = "all"     # "all" | "any"
    # 强制重跑时也要删、但【不能】作为完成判据的文件（断点/缓存）：
    # 它们会在步骤正常收尾时被代码自己删掉，一旦列进 markers，
    # is_done() 永远为 False —— 页面上这一步永远是「未运行」。
    clean_extra: tuple = ()
    logs: tuple = ()             # log files the UI can tail for this step
    llm_titles: tuple = ()       # gpt_log titles for per-step LLM stats
    needs_video: bool = False    # meaningless (skipped) for audio-only input

    def run(self):
        """Execute this step's callables in order (lazy imports)."""
        for module_path, func_name in self.calls:
            module = importlib.import_module(module_path)
            getattr(module, func_name)()

    def is_done(self) -> bool:
        if not self.markers:
            return False
        checks = [os.path.exists(m) for m in self.markers]
        return all(checks) if self.marker_mode == "all" else any(checks)


