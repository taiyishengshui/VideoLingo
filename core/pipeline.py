_BY_ID = {s.id: s for s in STEPS}
# 全局固定序号：与源码文件编号 _2…_12 对齐（第 10 步 = _10_gen_audio）。
# 不能用 audio_only 过滤后的下标，否则纯音频输入时序号会整体前移，
# 页面上的「第 N 步」和文档/口头的说法就对不上了（FR-21 / v1.26）。
STEP_NO = {s.id: i for i, s in enumerate(STEPS, 1)}


def get_step(step_id: str) -> Step:
    if step_id not in _BY_ID:
        raise KeyError(f"unknown step id: {step_id} (have: {', '.join(_BY_ID)})")
    return _BY_ID[step_id]


def get_steps(stage: str | None = None, audio_only: bool = False) -> list:
    """Steps in pipeline order, optionally filtered by stage. Video-only
    steps are dropped when the input is audio-only."""
    steps = [s for s in STEPS if stage is None or s.stage == stage]
    if audio_only:
        steps = [s for s in steps if not s.needs_video]
    return steps


def pipeline_status(audio_only: bool = False) -> list:
    """Serializable per-step status for the API."""
    return [
        {
            "id": s.id,
            "no": STEP_NO[s.id],
            "title": s.title,
            "stage": s.stage,
            "done": s.is_done(),
            "markers": list(s.markers),
            "logs": list(s.logs),
            "llm_titles": list(s.llm_titles),
        }
        for s in get_steps(audio_only=audio_only)
    ]
